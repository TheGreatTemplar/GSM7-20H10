class HelpDialog(QtWidgets.QDialog):
    def __init__(self, parent):
        super().__init__(parent)
        self.setWindowTitle("Справка · GSM7-20H10")
        self.resize(760, 580)
        layout = QtWidgets.QVBoxLayout(self)
        self.tabs = QtWidgets.QTabWidget()
        layout.addWidget(self.tabs)
        for title, html in HELP_PAGES:
            browser = QtWidgets.QTextBrowser()
            browser.document().addResource(QtGui.QTextDocument.ResourceType.ImageResource,
                QtCore.QUrl("gsmbench:mixer"), QtGui.QImage(str(Path(__file__).resolve().parent.parent / "img" / "mixer.png")))
            browser.setOpenExternalLinks(True)
            browser.document().setDefaultStyleSheet("a\n{\n    color: #45d7d0;\n}")
            browser.setHtml(html)
            self.tabs.addTab(browser, title)
        close = QtWidgets.QDialogButtonBox(QtWidgets.QDialogButtonBox.StandardButton.Close)
        close.button(QtWidgets.QDialogButtonBox.StandardButton.Close).setText("Закрыть")
        close.rejected.connect(self.close)
        layout.addWidget(close)


